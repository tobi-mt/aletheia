// Validate completeness
let errors = 0;
for (const [lang, map] of Object.entries(BOOK_NAMES)) {
  for (const book of CANONICAL_BOOKS) {
    if (!map[book]) {
      console.error(`Missing: ${lang}.${book}`);
      errors++;
    }
  }
  const extra = Object.keys(map).filter((b) => !CANONICAL_BOOKS.includes(b));
  if (extra.length) {
    console.warn(`Extra keys in ${lang}: ${extra.join(", ")}`);
  }
}
if (errors > 0) {
  console.error(`\n${errors} missing entries. Fix before writing.`);
  process.exit(1);
}

// Build TypeScript output
const lines = [
  "// AUTO-GENERATED by scripts/generate-scripture-book-names.mjs",
  "// Do not edit manually — run: node scripts/generate-scripture-book-names.mjs",
  "// Covers all 66 canonical Bible books across 10 non-English UI languages.",
  "",
  "export const localizedScriptureBookNamesGenerated = {",
];

for (const [lang, map] of Object.entries(BOOK_NAMES)) {
  lines.push(`  ${lang}: {`);
  for (const book of CANONICAL_BOOKS) {
    const name = map[book];
    lines.push(`    ${JSON.stringify(book)}: ${JSON.stringify(name)},`);
  }
  lines.push(`  },`);
}

lines.push("} as const;");
lines.push("");

const output = lines.join("\n");
