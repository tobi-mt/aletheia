#!/usr/bin/env node
// Builds src/lib/bible-paragraphs.generated.ts from the public-domain World English Bible USFM
// (https://ebible.org/Scriptures/eng-web_usfm.zip). Paragraph starts follow verse numbers, so the
// same map gives natural paragraph breaks for every translation the reader serves.
//
// Usage: node scripts/generate-bible-paragraphs.mjs <path-to-unzipped-eng-web-usfm>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const CANON = [
  "GEN", "EXO", "LEV", "NUM", "DEU", "JOS", "JDG", "RUT", "1SA", "2SA", "1KI", "2KI", "1CH", "2CH", "EZR", "NEH", "EST", "JOB", "PSA", "PRO",
  "ECC", "SNG", "ISA", "JER", "LAM", "EZK", "DAN", "HOS", "JOL", "AMO", "OBA", "JON", "MIC", "NAM", "HAB", "ZEP", "HAG", "ZEC", "MAL", "MAT",
  "MRK", "LUK", "JHN", "ACT", "ROM", "1CO", "2CO", "GAL", "EPH", "PHP", "COL", "1TH", "2TH", "1TI", "2TI", "TIT", "PHM", "HEB", "JAS", "1PE",
  "2PE", "1JN", "2JN", "3JN", "JUD", "REV",
];
// Reader book names, in the same order as CANON.
const BOOK_NAMES = [
  "Genesis", "Exodus", "Leviticus", "Numbers", "Deuteronomy", "Joshua", "Judges", "Ruth", "1 Samuel", "2 Samuel", "1 Kings", "2 Kings",
  "1 Chronicles", "2 Chronicles", "Ezra", "Nehemiah", "Esther", "Job", "Psalms", "Proverbs", "Ecclesiastes", "Song of Solomon", "Isaiah",
  "Jeremiah", "Lamentations", "Ezekiel", "Daniel", "Hosea", "Joel", "Amos", "Obadiah", "Jonah", "Micah", "Nahum", "Habakkuk", "Zephaniah",
  "Haggai", "Zechariah", "Malachi", "Matthew", "Mark", "Luke", "John", "Acts", "Romans", "1 Corinthians", "2 Corinthians", "Galatians",
  "Ephesians", "Philippians", "Colossians", "1 Thessalonians", "2 Thessalonians", "1 Timothy", "2 Timothy", "Titus", "Philemon", "Hebrews",
  "James", "1 Peter", "2 Peter", "1 John", "2 John", "3 John", "Jude", "Revelation",
];
// Prose paragraphs, poetry stanza breaks and section headings all start a new reading block.
const BREAK_MARKER = /^\\(p|m|pi\d?|pm[or]?|pc|po|cls|li\d?|lh|b|ms\d?|s\d?|qa|d)\b/;
const POETRY_MARKER = /^\\(q\d?|qr|qc|qm\d?)\b/;
const PROSE_MARKER = /^\\(p|m|pi\d?|pm[or]?|pc|po|cls|li\d?|lh)\b/;

// Collapses sorted verse numbers into "a-b" ranges.
const ranges = (verses) => {
  const out = [];
  for (const verse of verses) {
    const last = out[out.length - 1];
    if (last && verse === last[1] + 1) last[1] = verse;
    else out.push([verse, verse]);
  }
  return out.map(([from, to]) => (from === to ? `${from}` : `${from}-${to}`));
};

// Encodes one USFM book as `paragraph starts|poetry ranges` per chapter, joined by ";".
// bibleChapterLayout in src/lib/bible-paragraphs.ts decodes exactly this format.
export function encodeUsfmBook(usfm) {
  const chapters = {};
  const poetry = {};
  let chapter = 0;
  let pendingBreak = false;
  let inPoetry = false;
  for (const rawLine of usfm.split(/\r?\n/)) {
    const line = rawLine.trim();
    const chapterMatch = line.match(/^\\c\s+(\d+)/);
    if (chapterMatch) {
      chapter = Number(chapterMatch[1]);
      chapters[chapter] = [];
      poetry[chapter] = [];
      pendingBreak = true;
      continue;
    }
    if (!chapter) continue;
    if (BREAK_MARKER.test(line)) pendingBreak = true;
    if (POETRY_MARKER.test(line)) inPoetry = true;
    else if (PROSE_MARKER.test(line)) inPoetry = false;
    // A marker may share the line with the verse ("\p \v 3 ..."); each \v on the line is checked in order.
    for (const verseMatch of line.matchAll(/\\v\s+(\d+)/g)) {
      if (pendingBreak) chapters[chapter].push(Number(verseMatch[1]));
      if (inPoetry) poetry[chapter].push(Number(verseMatch[1]));
      pendingBreak = false;
    }
  }
  return Object.entries(chapters)
    .sort(([a], [b]) => Number(a) - Number(b))
    .map(([number, starts]) => {
      const lines = ranges([...new Set(poetry[number])]);
      return [...new Set(starts)].join(",") + (lines.length ? `|${lines.join(",")}` : "");
    })
    .join(";");
}

function main(sourceDir) {
  if (!sourceDir || !fs.existsSync(sourceDir)) {
    console.error("Pass the folder containing the unzipped eng-web USFM files.");
    process.exit(1);
  }
  const books = {};
  for (const file of fs.readdirSync(sourceDir).filter((name) => name.endsWith(".usfm"))) {
    const usfm = fs.readFileSync(path.join(sourceDir, file), "utf8");
    const code = usfm.match(/^\\id\s+(\S+)/m)?.[1];
    if (!code || !CANON.includes(code)) continue;
    books[code] = encodeUsfmBook(usfm);
  }

  const missing = CANON.filter((code) => !books[code]);
  if (missing.length) {
    console.error(`Missing books in source: ${missing.join(", ")}`);
    process.exit(1);
  }

  const output = `// Generated by scripts/generate-bible-paragraphs.mjs from the public-domain World English Bible USFM.
// Each book lists chapters separated by ";". A chapter is "paragraph-start verses|poetry verse ranges",
// e.g. "1,4|1-6" means paragraphs start at verses 1 and 4, and verses 1–6 are set as poetry lines.
// Do not edit by hand.
export const BIBLE_PARAGRAPH_STARTS: Record<string, string> = ${JSON.stringify(Object.fromEntries(CANON.map((code, index) => [BOOK_NAMES[index], books[code]])), null, 2)};
`;
  const target = path.join(path.dirname(new URL(import.meta.url).pathname), "..", "src", "lib", "bible-paragraphs.generated.ts");
  fs.writeFileSync(target, output);
  console.log(`Wrote ${path.relative(process.cwd(), target)} (${(output.length / 1024).toFixed(1)} KB, ${CANON.length} books)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main(process.argv[2]);
